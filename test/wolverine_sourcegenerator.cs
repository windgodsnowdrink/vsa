// GitHub Actions 示例
// 触发条件：Contracts 项目代码改动时，自动编译并发布到 GitHub Packages
name: Build & Publish Contracts

on:
  push:
    branches: [ main ]
    paths:
      - 'Contracts/**'          # 只在契约代码改动时触发

jobs:
  build-contracts:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Setup .NET
        uses: actions/setup-dotnet@v4
        with:
          dotnet-version: '8.x'

      - name: Restore
        run: dotnet restore Contracts/Contracts.csproj

      - name: Build (generates source)
        run: dotnet build Contracts/Contracts.csproj -c Release

      - name: Pack NuGet
        run: |
          dotnet pack Contracts/Contracts.csproj -c Release \
            -p:PackageVersion=1.$(date +%Y%m%d%H%M) \
            -o ./artifacts

      - name: Publish to GitHub Packages
        env:
          NUGET_AUTH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        run: |
          dotnet nuget push ./artifacts/*.nupkg \
            --source "https://nuget.pkg.github.com/${{ github.repository_owner }}/index.json" \
            --api-key $NUGET_AUTH_TOKEN \
            --skip-duplicate
