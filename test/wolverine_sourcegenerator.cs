// 生产的代码的使用
// 任意业务微服务（A/B/C）只引用 Contracts 项目
public class BindDeviceController : ControllerBase
{
    private readonly IServiceProvider _sp;
    public BindDeviceController(IServiceProvider sp) => _sp = sp;

    [HttpPost("bind")]
    public async Task<IActionResult> Bind([FromBody] BindRequest r)
    {
        var resp = await _sp.SendBindAsync(r.DeviceId, r.UserId); // 自动生成的扩展方法
        // var cmd = new BindDeviceCommand(r.DeviceId, r.UserId);
        // var resp = await bus.InvokeAsync<BindDeviceResult>(cmd);
        if (!resp.Result.Success)
            return BadRequest(resp.Result.Error);
        return Ok();
    }
}

