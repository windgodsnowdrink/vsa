// WolverineMessageGenerator/Generator.cs
[Generator]
public class MessageContractGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext ctx)
    {
        // 注册语法接收器，收集标记了 [MessageContract] 的接口
        ctx.RegisterForSyntaxNotifications(() => new InterfaceReceiver());
    }

    public void Execute(GeneratorExecutionContext ctx)
    {
        if (ctx.SyntaxReceiver is not InterfaceReceiver receiver) return;

        foreach (var iface in receiver.CandidateInterfaces)
        {
            var model = ctx.Compilation.GetSemanticModel(iface.SyntaxTree);
            var ifaceSymbol = model.GetDeclaredSymbol(iface) as INamedTypeSymbol;
            if (ifaceSymbol == null) continue;

            // 只处理标记了 MessageContractAttribute 的接口
            var hasAttr = ifaceSymbol.GetAttributes()
                .Any(a => a.AttributeClass?.Name == nameof(MessageContractAttribute));
            if (!hasAttr) continue;

            var source = GenerateCodeForInterface(ifaceSymbol);
            ctx.AddSource($"{ifaceSymbol.Name}_Generated.cs", source);
        }
    }

    private string GenerateCodeForInterface(INamedTypeSymbol iface)
    {
        var ns = iface.ContainingNamespace.ToDisplayString();
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using System;");
        sb.AppendLine("using Wolverine;");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();

        // 1️⃣ 为每个方法生成 Record（如果返回 void → Event）
        foreach (var m in iface.GetMembers().OfType<IMethodSymbol>())
        {
            var methodName = m.Name;
            var parameters = m.Parameters;
            var returnType = m.ReturnType;

            // 生成 record 名称
            var recordName = methodName;

            // 参数列表转成 record 属性
            var props = string.Join(", ",
                parameters.Select(p => $"{p.Type.ToDisplayString()} {p.Name}"));
            sb.AppendLine($"public sealed record {recordName}({props});");
            sb.AppendLine();

            // 如果返回值不是 void，生成 Response record
            if (!returnType.Name.Equals("Void"))
            {
                var respName = $"{recordName}Result";
                // 简单假设返回值是 primitive 或另一 record；这里直接转成属性
                // 为演示起见，使用单属性 Response（真实项目可自行扩展）
                sb.AppendLine($"public sealed record {respName}({returnType.ToDisplayString()} Result);");
                sb.AppendLine();
            }
        }

        // 2️⃣ 生成 MessageBus 扩展方法（帮助 Publish/Invoke）
        sb.AppendLine($"public static class {iface.Name}Extensions");
        sb.AppendLine("{");
        sb.AppendLine("    public static IMessageBus GetBus(this IServiceProvider sp) => sp.GetService<IMessageBus>();");
        sb.AppendLine();

        foreach (var m in iface.GetMembers().OfType<IMethodSymbol>())
        {
            var methodName = m.Name;
            var parameters = m.Parameters;
            var returnType = m.ReturnType;
            var paramList = string.Join(", ", parameters.Select(p => $"{p.Type.ToDisplayString()} {p.Name}"));
            var argList   = string.Join(", ", parameters.Select(p => p.Name));

            // Publish (Event) 方法
            if (returnType.Name.Equals("Void"))
            {
                sb.AppendLine($"    public static async Task Publish{methodName}Async(this IServiceProvider sp, {paramList})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var msg = new {methodName}({argList});");
                sb.AppendLine("        await sp.GetBus().PublishAsync(msg);");
                sb.AppendLine("    }");
                sb.AppendLine();
            }
            else // Request‑Response
            {
                var respRecord = $"{methodName}Result";
                sb.AppendLine($"    public static async Task<{respRecord}> Send{methodName}Async(this IServiceProvider sp, {paramList})");
                sb.AppendLine("    {");
                sb.AppendLine($"        var msg = new {methodName}({argList});");
                sb.AppendLine($"        return await sp.GetBus().InvokeAsync<{respRecord}>(msg);");
                sb.AppendLine("    }");
                sb.AppendLine();
            }
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    // -------------------------------------------------
    // 接收器：找到所有 interface 语法节点
    private class InterfaceReceiver : ISyntaxReceiver
    {
        public List<InterfaceDeclarationSyntax> CandidateInterfaces { get; } = new();

        public void OnVisitSyntaxNode(SyntaxNode node)
        {
            if (node is InterfaceDeclarationSyntax ids && ids.AttributeLists.Count > 0)
                CandidateInterfaces.Add(ids);
        }
    }
}

