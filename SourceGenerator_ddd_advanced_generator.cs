        {{
            if (Value == default({vo.UnderlyingType}))
                throw new ArgumentException(""Value cannot be empty"", nameof(Value));
        }}
    }}
}}";
    }
}

// 3. 微服务模板代码
[Generator]
public class MicroserviceGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext context)
    {
        context.RegisterForSyntaxNotifications(() => new MicroserviceSyntaxReceiver());
    }

    public void Execute(GeneratorExecutionContext context)
    {
        if (!(context.SyntaxContextReceiver is MicroserviceSyntaxReceiver receiver))
            return;

        foreach (var service in receiver.Services)
        {
            // 生成gRPC服务
            var grpcService = GenerateGrpcService(service);
            context.AddSource($"{service.Name}GrpcService.g.cs", SourceText.From(grpcService, Encoding.UTF8));

            // 生成Kafka消费者
            var kafkaConsumer = GenerateKafkaConsumer(service);
            context.AddSource($"{service.Name}KafkaConsumer.g.cs", SourceText.From(kafkaConsumer, Encoding.UTF8));
        }
    }

    private string GenerateGrpcService(ServiceInfo service)
    {
        return $@"// <auto-generated/>
using Grpc.Core;
using {service.Namespace}.Application.Interfaces;

namespace {service.Namespace}.Services
{{
    public class {service.Name}GrpcService : {service.Name}Service.{service.Name}ServiceBase
    {{
        private readonly I{service.Name}AppService _appService;

        public {service.Name}GrpcService(I{service.Name}AppService appService)
        {{
            _appService = appService;
        }}

        public override async Task<Get{service.Name}Response> Get{service.Name}(Get{service.Name}Request request, ServerCallContext context)
        {{
            var dto = await _appService.GetByIdAsync(request.Id);
            return new Get{service.Name}Response {{ Data = dto }};
        }}
    }}
}}";
    }

    private string GenerateKafkaConsumer(ServiceInfo service)
    {
        return $@"// <auto-generated/>
using Confluent.Kafka;
using MediatR;
using {service.Namespace}.Domain.Events;

namespace {service.Namespace}.Services
{{
    public class {service.Name}KafkaConsumer : BackgroundService
    {{
        private readonly IConsumer<Ignore, string> _consumer;
        private readonly IMediator _mediator;

        public {service.Name}KafkaConsumer(IConsumer<Ignore, string> consumer, IMediator mediator)
        {{
            _consumer = consumer;
            _mediator = mediator;
        }}

        protected override async Task ExecuteAsync(CancellationToken stoppingToken)
        {{
            _consumer.Subscribe(""{service.Name}Events"");

            while (!stoppingToken.IsCancellationRequested)
            {{
                try
                {{
                    var consumeResult = _consumer.Consume(stoppingToken);
                    var @event = JsonSerializer.Deserialize<I{service.Name}DomainEvent>(consumeResult.Message.Value);
                    await _mediator.Publish(@event, stoppingToken);
                }}
                catch (Exception ex)
                {{
                    // 错误处理
                }}
            }}
        }}
    }}
}}";
    }
}

// 语法接收器
public class DomainEventSyntaxReceiver : ISyntaxContextReceiver
{
    public List<EntityInfo> Entities { get; } = new();

    public void OnVisitSyntaxNode(GeneratorSyntaxContext context)
    {
        if (context.Node is ClassDeclarationSyntax classDecl &&
            classDecl.AttributeLists.Any(a => a.Attributes.Any(at => at.Name.ToString().Contains("AggregateRoot"))))
        {
            var model = context.SemanticModel.GetDeclaredSymbol(classDecl);
            if (model != null)
            {
                Entities.Add(new EntityInfo
                {
                    Name = model.Name,
                    Namespace = model.ContainingNamespace.ToDisplayString()
                });
            }
        }
    }
}

public class ValueObjectSyntaxReceiver : ISyntaxContextReceiver
{
    public List<ValueObjectInfo> ValueObjects { get; } = new();

    public void OnVisitSyntaxNode(GeneratorSyntaxContext context)
    {
        if (context.Node is ClassDeclarationSyntax classDecl &&
            classDecl.AttributeLists.Any(a => a.Attributes.Any(at => at.Name.ToString().Contains("ValueObject"))))
        {
            var model = context.SemanticModel.GetDeclaredSymbol(classDecl);
            if (model != null)
            {
                ValueObjects.Add(new ValueObjectInfo
                {
                    Name = model.Name,
                    Namespace = model.ContainingNamespace.ToDisplayString(),
                    UnderlyingType = "string" // 默认类型，可从属性获取
                });
            }
        }
    }
}

