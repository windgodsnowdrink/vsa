// 1. 领域事件实现
[Generator]
public class DomainEventGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext context)
    {
        context.RegisterForSyntaxNotifications(() => new DomainEventSyntaxReceiver());
    }

    public void Execute(GeneratorExecutionContext context)
    {
        if (!(context.SyntaxContextReceiver is DomainEventSyntaxReceiver receiver))
            return;

        foreach (var entity in receiver.Entities)
        {
            // 生成领域事件接口
            var eventInterface = GenerateEventInterface(entity);
            context.AddSource($"I{entity.Name}DomainEvent.g.cs", SourceText.From(eventInterface, Encoding.UTF8));

            // 生成基础领域事件
            var baseEvent = GenerateBaseDomainEvent(entity);
            context.AddSource($"{entity.Name}DomainEvent.g.cs", SourceText.From(baseEvent, Encoding.UTF8));

            // 生成具体领域事件
            var createdEvent = GenerateCreatedEvent(entity);
            context.AddSource($"{entity.Name}CreatedEvent.g.cs", SourceText.From(createdEvent, Encoding.UTF8));
        }
    }

    private string GenerateEventInterface(EntityInfo entity)
    {
        return $@"// <auto-generated/>
using MediatR;

namespace {entity.Namespace}.Domain.Events
{{
    public interface I{entity.Name}DomainEvent : INotification
    {{
        {entity.Name} Entity {{ get; }}
    }}
}}";
    }

    private string GenerateBaseDomainEvent(EntityInfo entity)
    {
        return $@"// <auto-generated/>
using MediatR;

namespace {entity.Namespace}.Domain.Events
{{
    public abstract class {entity.Name}DomainEvent : I{entity.Name}DomainEvent
    {{
        public {entity.Name} Entity {{ get; }}

        protected {entity.Name}DomainEvent({entity.Name} entity)
        {{
            Entity = entity;
        }}
    }}
}}";
    }

    private string GenerateCreatedEvent(EntityInfo entity)
    {
        return $@"// <auto-generated/>
namespace {entity.Namespace}.Domain.Events
{{
    public class {entity.Name}CreatedEvent : {entity.Name}DomainEvent
    {{
        public {entity.Name}CreatedEvent({entity.Name} entity) : base(entity)
        {{
        }}
    }}
}}";
    }
}

